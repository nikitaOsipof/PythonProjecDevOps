'''
Polars позволяет сортировать данные внутри окна как по одной, так и по нескольким колонкам одновременно,
причем с разным направлением сортировки (например, одну по возрастанию, другую — по убыванию).

Пример 1. Простая сортировка и ранжирование внутри окна

Требуется присвоить ранг сотрудникам внутри каждого департамента на основе их зарплаты (от большей к меньшей).
Если зарплаты одинаковые, первыми должны идти те, кто пришел в компанию раньше (по дате).
'''

import polars as pl
from datetime import date

# Исходный датасет
df = pl.DataFrame({
    "department": ["IT", "IT", "IT", "HR", "HR"],
    "name": ["Иван", "Мария", "Алексей", "Анна", "Елена"],
    "salary": [120, 250, 110, 350, 160],
    "hire_date": [date(2023, 1, 15), date(2022, 5, 10), date(2024, 3, 1), date(2021, 8, 20), date(2023, 11, 1)]
})

# Сортировка внутри окна по двум колонкам
result = df.with_columns(
    pl.col("name")
    .sort_by(["salary", "hire_date"], descending=[True, False]) # Зарплата по убыванию, дата по возрастанию
    .rank(method="ordinal")                                     # Порядковый ранг
    .over("department")
    .alias("rank_within_dept")
)

print(result)


'''
Пример 2. Оконные функции, зависящие от порядка строк (Кумулятивная сумма и скользящее среднее)

Требуется подсчитать нарастающий итог продаж для каждого магазина, 
где записи должны строго идти по дате от старых к новым:
'''

sales_df = pl.DataFrame({
    "store": ["Магазин А", "Магазин А", "Магазин А", "Магазин Б", "Магазин Б"],
    "date": ["2026-01-01", "2026-01-03", "2026-01-02", "2026-01-01", "2026-01-02"],
    "amount": [1000, 1500, 1200, 800, 2000]
})

running_total = sales_df.with_columns(
    # Сначала сортируем сумму продаж по дате, затем считаем кумулятивную сумму внутри магазина
    pl.col("amount")
    .sort_by("date", descending=False)
    .cum_sum()
    .over("store")
    .alias("running_total")
).sort(["store", "date"]) # Финальная сортировка всей таблицы для красивого вывода

print(running_total)

'''
Практический пример: Кастомный потоковый сенсор
Задача. Представим, что пишем пайплайн, который считывает показания с температурного датчика на заводе. 
Датчик выдает миллионы записей, но нам для аналитики нужны только аномально высокие температуры (> 100°C).
Напишем класс, который лениво фильтрует этот бесконечный поток, потребляя ровно 0 байт памяти на хранение истории.
'''

import random

# Имитируем «грязный» бесконечный поток данных с датчика
def raw_sensor_stream():
    while True:
        yield random.randint(20, 150) # Выдает случайную температуру от 20 до 150 градусов

class HighTemperatureFilter:
    """
    Кастомный класс-итератор, реализующий протокол Python 'под капотом'
    """
    def __init__(self, data_source, threshold=100):
        # Принимаем любой итерируемый источник (генератор, файл, список)
        self.source = iter(data_source)
        self.threshold = threshold

    def __iter__(self):
        # По протоколу метод __iter__ обязан вернуть сам объект-итератор
        return self

    def __next__(self):
        # Метод __next__ управляет движением конвейера
        while True:
            # Запрашиваем элемент у исходного источника
            current_value = next(self.source)
            
            # Если значение превышает порог — отдаем его наружу
            if current_value > self.threshold:
                return current_value
            
            # Если значение маленькое, цикл while продолжается, 
            # и мы берем следующее число, не накапливая мусор в RAM!

# --- ИСПОЛЬЗОВАНИЕ В ПАЙПЛАЙНЕ ---

# 1. Создаем бесконечный источник данных (память = 0) 
raw_data = raw_sensor_stream()

# 2. Оборачиваем его в наш кастомный фильтр-итератор
alert_system = HighTemperatureFilter(raw_data, threshold=120)

print("Запуск мониторинга критических аномалий (выведем первые 5):\n")

# 3. Наш класс идеально встраивается в стандартный цикл for!
for count, anomaly in enumerate(alert_system, 1):
    print(f"⚠️ Аномалия №{count}: Зафиксирован перегрев: {anomaly}°C!")
    
    if count == 5:
        print("\n[LOG] Мониторинг приостановлен.")
        break

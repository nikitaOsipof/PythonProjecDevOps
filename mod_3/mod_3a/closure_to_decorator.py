# Есть замыкание:
def foo(y):
    def bar(x):
        return x + y
    return bar

b = foo(1)
print(b(2))

# Как эта же задача будет с помощью декоратора?

# Вариант 1: Простой декоратор (с жестко заданным сдвигом)
# Представим, что есть какая-то функция, возвращающая число (например, объем скачанных данных в ETL),
# и хотим всегда прибавлять к её результату единицу.

# теперь принимает не число y, а ФУНКЦИЮ func
def my_decorator(func):
    def bar(arg):
        # Вызываем исходную функцию и прибавляем к её результату 1
        return func(arg) + 1
    return bar

# Исходная функция, которая просто возвращает переданное число
@my_decorator
def get_base_value(x):
    return x

# get_base_value(2) вернет 2, а декоратор прибавит 1. Итог: 3
print(get_base_value(2))  # Выведет: 3

# Вариант 2: Декоратор с аргументом
# сохранить возможность динамически передавать число y - используем декоратор, который сам принимает аргументы.

# 1-й уровень: Принимает переменную y (как функция foo)
def foo_decorator(y):
    # 2-й уровень: Принимает функцию как объект (высший порядок)
    def actual_decorator(func):
        # 3-й уровень: Принимает аргументы для исходной функции
        def bar(x):
            # Замыкание помнит и y (с 1-го этажа), и func (со 2-го)
            return func(x) + y
        return bar
    return actual_decorator

# Базовая функция
def get_base(x):
    return x

# Применяем декоратор и передаем y = 1 (аналог b = foo(1))
# Теперь get_base модифицирован с помощью foo_decorator
@foo_decorator(y=1)
def augmented_base(x):
    return x

# Проверяем (аналог b(2))
print(augmented_base(2))  # Выведет: 3
